//! Stable educational chunk policies over byte slices.
//! Boundary fingerprints select cuts. Byte comparison establishes equality.

/// Boundary algorithm. Gear policies have distinct output contracts.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum Policy {
    /// Equal-sized chunks.
    Fixed,
    /// Recompute a base-257 window at each eligible position.
    Direct,
    /// Remove the departing contribution and append one byte.
    Rolling,
    /// Shift and add a fixed table entry for every byte.
    Gear,
    /// Gear with stricter selection below the target size.
    Normalized,
}

/// Validated chunk-size and fingerprint settings.
#[derive(Clone, Copy, Debug)]
pub struct Config {
    min: usize,
    target: usize,
    max: usize,
    window: usize,
}
impl Config {
    /// Require window > 0, 2 <= target <= `usize::MAX / 2` with target a power of two,
    /// and window <= min <= target <= max. The target bound keeps 2 * target - 1 in range.
    #[must_use]
    pub fn new(min: usize, target: usize, max: usize, window: usize) -> Option<Self> {
        (window > 0
            && target >= 2
            && window <= min
            && min <= target
            && target.is_power_of_two()
            && target <= max
            && target <= usize::MAX / 2)
            .then_some(Self {
                min,
                target,
                max,
                window,
            })
    }
}

/// Fixed Gear table v1, generated by a specified integer mixer.
#[must_use]
pub const fn gear_table() -> [u64; 256] {
    let mut table = [0; 256];
    let mut i = 0;
    let mut state = 1_u64;
    while i < 256 {
        state = state.wrapping_add(0x9e37_79b9_7f4a_7c15);
        let mut z = state;
        z = (z ^ (z >> 30)).wrapping_mul(0xbf58_476d_1ce4_e5b9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94d0_49bb_1331_11eb);
        table[i] = z ^ (z >> 31);
        i += 1;
    }
    table
}
const GEAR: [u64; 256] = gear_table();

/// Base-257 fingerprint with explicitly wrapping 64-bit arithmetic.
#[must_use]
pub fn fingerprint(bytes: &[u8]) -> u64 {
    bytes.iter().fold(0_u64, |h, &b| {
        h.wrapping_mul(257).wrapping_add(u64::from(b))
    })
}

/// Return increasing exclusive chunk ends. Empty input has no chunks.
///
/// Every nonfinal chunk lies in [min, max]. The final chunk may be shorter.
/// Direct and Rolling have identical boundaries. Fingerprint state resets at cuts.
/// The slice API processes a complete object. Transport fragments must preserve state.
#[must_use]
pub fn boundaries(bytes: &[u8], config: Config, policy: Policy) -> Vec<usize> {
    let mut ends = Vec::new();
    let mut start = 0;
    let mut h = 0_u64;
    let mut power = 1_u64;
    for _ in 1..config.window {
        power = power.wrapping_mul(257);
    }
    for (i, &byte) in bytes.iter().enumerate() {
        let len = i + 1 - start;
        match policy {
            Policy::Rolling => {
                if len > config.window {
                    h = h.wrapping_sub(u64::from(bytes[i - config.window]).wrapping_mul(power));
                }
                h = h.wrapping_mul(257).wrapping_add(u64::from(byte));
            }
            Policy::Gear | Policy::Normalized => h = (h << 1).wrapping_add(GEAR[usize::from(byte)]),
            Policy::Fixed | Policy::Direct => {}
        }
        let cut = if policy == Policy::Fixed {
            len == config.target
        } else if len >= config.max {
            true
        } else if len < config.min {
            false
        } else {
            if policy == Policy::Direct {
                h = fingerprint(&bytes[i + 1 - config.window..=i]);
            }
            let mask = if policy == Policy::Normalized {
                if len < config.target {
                    2 * config.target - 1
                } else {
                    config.target / 2 - 1
                }
            } else {
                config.target - 1
            };
            h & u64::try_from(mask).unwrap_or(u64::MAX) == 0
        };
        if cut {
            ends.push(i + 1);
            start = i + 1;
            h = 0;
        }
    }
    if start < bytes.len() {
        ends.push(bytes.len());
    }
    ends
}

/// Exact matching with hash filtering. Empty patterns match every byte boundary.
/// Verification can cost O(n*m) for dense true matches or colliding windows.
#[must_use]
pub fn exact_matches(text: &[u8], pattern: &[u8]) -> Vec<usize> {
    if pattern.is_empty() {
        return (0..=text.len()).collect();
    }
    if pattern.len() > text.len() {
        return Vec::new();
    }
    let wanted = fingerprint(pattern);
    let mut power = 1_u64;
    for _ in 1..pattern.len() {
        power = power.wrapping_mul(257);
    }
    let mut h = fingerprint(&text[..pattern.len()]);
    let mut result = Vec::new();
    for i in 0..=text.len() - pattern.len() {
        if h == wanted && &text[i..i + pattern.len()] == pattern {
            result.push(i);
        }
        if i + pattern.len() < text.len() {
            h = h
                .wrapping_sub(u64::from(text[i]).wrapping_mul(power))
                .wrapping_mul(257)
                .wrapping_add(u64::from(text[i + pattern.len()]));
        }
    }
    result
}

/// Deterministic benchmark input. `zero` and `periodic` exercise structured data.
///
/// # Panics
///
/// Panics on an unknown `shape`, for `n == 0` as well.
#[must_use]
pub fn fixture(n: usize, shape: &str) -> Vec<u8> {
    assert!(
        matches!(shape, "random" | "zero" | "periodic"),
        "unknown shape {shape}; use random, zero, or periodic"
    );
    let mut state = 7_u64;
    (0..n)
        .map(|i| {
            state ^= state << 13;
            state ^= state >> 7;
            state ^= state << 17;
            match shape {
                "zero" => 0,
                "periodic" => u8::try_from(i % 7).unwrap_or(0),
                _ => state.to_le_bytes()[0],
            }
        })
        .collect()
}
